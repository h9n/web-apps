#!/usr/bin/env python3
"""Generate ctrl_deck neon: 10 s, 30 fps, headerless GRB, linear gamma (.10g).

Five exact authored stops, 2 seconds apart, cosine easing to linger near each
colour. Sample [0,1), including the orange→lime return, without duplicate end.
Python standard library only. Run --check to verify the checked-in bytes.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path

NAME = 'ctrl-deck-neon.30fps.10g.0dv'
FPS = 30
FRAMES = 300
PALETTE = ((199,255,62),(53,232,255),(255,77,166),(167,139,250),(255,146,87))

def generate():
    data = bytearray()
    for frame in range(FRAMES):
        index, offset = divmod(frame,60)
        blend = (1-math.cos(math.pi*offset/60))/2
        a,b = PALETTE[index], PALETTE[(index+1)%len(PALETTE)]
        r,g,b = (round(x+(y-x)*blend) for x,y in zip(a,b))
        data.extend((g,r,b))
    return bytes(data)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    path=Path(__file__).resolve().parent/NAME
    data=generate()
    if args.check: assert path.read_bytes()==data, 'Generated bytes differ'
    else: path.write_bytes(data)
    print(json.dumps({'asset':NAME,'bytes':len(data),'frames':FRAMES,'fps':FPS,'seconds':FRAMES/FPS,'order':'GRB','gamma':1,'sha256':hashlib.sha256(data).hexdigest()},indent=2))
